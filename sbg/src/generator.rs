//! C# proxy generator
//!
//! Generates C# proxy classes from extension metadata and optionally
//! includes user-provided C# sources so they become visible to JS at runtime.

use crate::metadata_reader::{ExtensionMetadata, MethodMetadata, PropertyMetadata};
use anyhow::Result;
use std::fs;
use std::path::{Path, PathBuf};

const GENERATED_FILE_HEADER: &str = "/* AUTO-GENERATED FILE. DO NOT MODIFY.\n * This class was automatically generated by the\n * static binding generator from the resources it found.\n * Please do not modify by hand.\n */\n\n#nullable enable\n\n";

/// Generates proxy C# source and project files.
pub struct Generator {
    output_dir: PathBuf,
    target_framework: String,
    target_platform_min_version: Option<String>,
    use_uwp: bool,
    app_sources_dirs: Vec<PathBuf>,
}

impl Generator {
    /// Create a new generator
    pub fn new(
        output_dir: &Path,
        target_framework: &str,
        target_platform_min_version: Option<&str>,
        use_uwp: bool,
        app_sources_dirs: Vec<PathBuf>,
    ) -> Self {
        Self {
            output_dir: output_dir.to_path_buf(),
            target_framework: target_framework.to_string(),
            target_platform_min_version: target_platform_min_version.map(str::to_string),
            use_uwp,
            app_sources_dirs,
        }
    }

    /// Generate C# proxy code and project files
    pub fn generate(&self, metadata: &[ExtensionMetadata]) -> Result<(PathBuf, usize)> {
        let project_dir = self.output_dir.join("NSWinRTProxies");
        fs::create_dir_all(&project_dir)?;

        self.generate_csproj(&project_dir)?;
        self.generate_dispatcher_support(&project_dir)?;

        for ext_meta in metadata {
            self.generate_proxy_class(&project_dir, ext_meta)?;
        }

        // Do not emit a separate AssemblyInfo.cs - modern SDKs generate assembly
        // attributes automatically (and may add platform attributes). Emitting our
        // own AssemblyInfo causes duplicate attribute errors, so skip it.

        let copied_sources = self.copy_app_sources(&project_dir)?;

        Ok((project_dir.join("NSWinRTProxies.csproj"), copied_sources))
    }

    fn generate_csproj(&self, project_dir: &Path) -> Result<()> {
        let target_platform_min_version = self
            .target_platform_min_version
            .as_ref()
            .map(|version| {
                format!(
                    "    <TargetPlatformMinVersion>{}</TargetPlatformMinVersion>\n",
                    version
                )
            })
            .unwrap_or_default();
        let use_uwp = if self.use_uwp {
            "    <UseUwp>true</UseUwp>\n"
        } else {
            ""
        };
        let csproj_content = format!(
            r#"<Project Sdk="Microsoft.NET.Sdk">

  <PropertyGroup>
    <TargetFramework>{}</TargetFramework>
{}{}    <OutputType>Library</OutputType>
    <RootNamespace>NSWinRTProxies</RootNamespace>
    <AssemblyName>NSWinRTProxies</AssemblyName>
    <LangVersion>latest</LangVersion>
    <Nullable>enable</Nullable>
    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>
  </PropertyGroup>

  <ItemGroup>
    <PackageReference Include="Microsoft.Windows.SDK.BuildTools" Version="10.0.22621.756" />
  </ItemGroup>

</Project>
"#,
            self.target_framework, target_platform_min_version, use_uwp
        );

        fs::write(project_dir.join("NSWinRTProxies.csproj"), csproj_content)?;
        Ok(())
    }

    fn generate_proxy_class(&self, project_dir: &Path, ext_meta: &ExtensionMetadata) -> Result<()> {
        let namespace = proxy_namespace(ext_meta);
        let class_name = proxy_class_name(ext_meta);
        let js_type_name = ext_meta
            .type_name
            .clone()
            .unwrap_or_else(|| format!("{}.{}", namespace, class_name));
        let filename = format!("{}_{}.g.cs", namespace.replace('.', "_"), class_name);
        let filepath = project_dir.join(&filename);

        let base_type = proxy_base_type(ext_meta);
        let has_real_base = base_type != "object";

        // Every base-class override JS asked for, resolved to its REAL signature from WinRT
        // metadata (see signature_resolver) — a method that can't be resolved (unknown to
        // metadata, or a JS-only helper with no C# counterpart) is skipped with a warning rather
        // than emitted with a guessed signature that either won't compile as an `override` or,
        // worse, silently compiles as an unrelated new method that never actually overrides
        // anything.
        let raw_base_name = ext_meta.base_class.as_deref().unwrap_or("");
        let mut resolved_methods: Vec<MethodMetadata> = Vec::new();
        if has_real_base {
            for method in &ext_meta.methods {
                match crate::signature_resolver::resolve_method(raw_base_name, &method.name) {
                    Some(r) => resolved_methods.push(MethodMetadata {
                        name: r.name,
                        return_type: r.return_type,
                        parameters: r.parameters,
                        modifier: r.modifier_override.unwrap_or("public override").to_string(),
                    }),
                    None => eprintln!(
                        "[sbg] warning: no known signature for {}.{} — skipping (extend the WinRT metadata lookup or check the method name)",
                        raw_base_name, method.name
                    ),
                }
            }
        }

        // Every interface JS asked to implement — the CLR requires ALL of an interface's
        // members implemented, so (unlike base-class overrides) these are never JS-override-
        // filtered: every resolved method/property gets a stub, forwarding to
        // ProxyDispatcher exactly like a base override does. An interface that can't be
        // resolved is skipped entirely (with a warning) — its members are unknown, so no
        // compilable, contract-complete implementation can be emitted for it.
        let mut interface_clause_names: Vec<String> = Vec::new();
        let mut interface_methods: Vec<MethodMetadata> = Vec::new();
        let mut interface_properties: Vec<PropertyMetadata> = Vec::new();
        for iface_name in &ext_meta.interfaces {
            match crate::signature_resolver::resolve_interface_members(iface_name) {
                Some((methods, properties)) => {
                    interface_clause_names.push(iface_name.clone());
                    interface_methods.extend(methods.into_iter().map(|r| {
                        // A member whose name collides with an inherited System.Object virtual
                        // (e.g. Windows.Foundation.IStringable.ToString) must be an `override`,
                        // not a bare `public` method — the latter only hides the base member
                        // (CS0114) instead of properly overriding it/satisfying the interface via
                        // the object virtual CsWinRT expects.
                        let modifier = if is_object_virtual(&r.name) {
                            "public override"
                        } else {
                            "public"
                        };
                        MethodMetadata {
                            name: r.name,
                            return_type: r.return_type,
                            parameters: r.parameters,
                            modifier: modifier.to_string(),
                        }
                    }));
                    interface_properties.extend(properties.into_iter().map(|r| PropertyMetadata {
                        name: r.name,
                        prop_type: r.prop_type,
                        is_readable: r.is_readable,
                        is_writable: r.is_writable,
                    }));
                }
                None => eprintln!(
                    "[sbg] warning: could not resolve interface {} — skipping (not found in WinRT metadata)",
                    iface_name
                ),
            }
        }

        // `: object` is never valid C# (every class already derives from object implicitly) —
        // omit the base type entirely when there's no real base class, and only join with `, `
        // when there's more than one entry.
        let mut clause_parts: Vec<&str> = Vec::new();
        if has_real_base {
            clause_parts.push(base_type.as_str());
        }
        for name in &interface_clause_names {
            clause_parts.push(name.as_str());
        }
        let base_clause = if clause_parts.is_empty() {
            String::new()
        } else {
            format!(" : {}", clause_parts.join(", "))
        };

        let type_name_literal = csharp_string_literal(js_type_name.as_str());
        let class_name_literal = csharp_string_literal(class_name.as_str());
        let property_modifier = if has_real_base { "public override" } else { "public" };

        // Pre-size the buffer: header ~400 bytes + ~150 per method + ~120 per property
        let method_count = resolved_methods.len() + interface_methods.len();
        let property_count = ext_meta.properties.len() + interface_properties.len();
        let capacity = 400 + method_count * 150 + property_count * 120;
        let mut class_code = String::with_capacity(capacity);
        class_code.push_str(GENERATED_FILE_HEADER);
        class_code.push_str("using System;\nusing NativeScriptGeneratedProxies;\n\n");
        class_code.push_str(&format!("namespace {}\n{{\n", namespace));
        class_code.push_str(&format!(
            "    /// <summary>\n    /// Auto-generated proxy for JS extension type: {}\n    /// </summary>\n    public class {}{}\n    {{\n        public const string __NsTypeName = {};\n        public const string __NsGeneratedClassName = {};\n\n        public {}()\n        {{\n            ProxyDispatcher.InitializeInstance(this, __NsTypeName);\n        }}\n\n",
            js_type_name,
            class_name,
            base_clause,
            type_name_literal,
            class_name_literal,
            class_name,
        ));

        for prop in &ext_meta.properties {
            class_code.push_str(&self.generate_property(prop, property_modifier));
        }
        for prop in &interface_properties {
            class_code.push_str(&self.generate_property(prop, "public"));
        }

        for method in &resolved_methods {
            class_code.push_str(&self.generate_method(method, "public override"));
        }
        for method in &interface_methods {
            class_code.push_str(&self.generate_method(method, "public"));
        }

        class_code.push_str("    }\n}\n");

        fs::write(&filepath, class_code)?;
        Ok(())
    }

    fn generate_property(&self, prop: &PropertyMetadata, modifier: &str) -> String {
        let prop_type = normalize_csharp_type(prop.prop_type.as_str());
        let property_name = sanitize_identifier(prop.name.as_str());
        let mut code = format!(
            "        {} {} {}\n        {{\n",
            modifier, prop_type, property_name
        );

        if prop.is_readable {
            code.push_str(&format!(
                "            get => ProxyDispatcher.GetProperty<{}>(this, \"{}\");\n",
                prop_type, property_name
            ));
        }
        if prop.is_writable {
            code.push_str(&format!(
                "            set => ProxyDispatcher.SetProperty(this, \"{}\", value);\n",
                property_name
            ));
        }

        code.push_str("        }\n\n");
        code
    }

    fn generate_method(&self, method: &MethodMetadata, _modifier: &str) -> String {
        let modifier = method.modifier.as_str();
        let params = method
            .parameters
            .iter()
            .enumerate()
            .map(|(index, (name, typ))| {
                format!(
                    "{} {}",
                    normalize_csharp_type(typ.as_str()),
                    sanitize_parameter_name(name.as_str(), index)
                )
            })
            .collect::<Vec<_>>()
            .join(", ");

        let return_type = normalize_csharp_type(method.return_type.as_str());
        let args = method
            .parameters
            .iter()
            .enumerate()
            .map(|(index, (name, _))| sanitize_parameter_name(name.as_str(), index))
            .collect::<Vec<_>>();
        let args_body = if args.is_empty() {
            "Array.Empty<object>()".to_string()
        } else {
            format!("new object[] {{ {} }}", args.join(", "))
        };
        let method_name = sanitize_identifier(method.name.as_str());
        let body = if return_type == "void" {
            format!(
                "            ProxyDispatcher.InvokeVoid(this, \"{}\", {});",
                method_name, args_body
            )
        } else {
            format!(
                "            return ProxyDispatcher.InvokeMethod<{}>(this, \"{}\", {});",
                return_type, method_name, args_body
            )
        };

        format!(
            "        {} {} {}({})\n        {{\n{}\n        }}\n\n",
            modifier, return_type, method_name, params, body
        )
    }

    fn generate_dispatcher_support(&self, project_dir: &Path) -> Result<()> {
        let support = format!(
            "{}using System;\nusing System.Globalization;\n\nnamespace NativeScriptGeneratedProxies\n{{\n    public static class ProxyDispatcher\n    {{\n        public static Func<object, string, object[], object?>? JsInvokeMethod {{ get; set; }}\n        public static Action<object, string, object[]>? JsInvokeVoid {{ get; set; }}\n        public static Func<object, string, object?>? JsGetProperty {{ get; set; }}\n        public static Action<object, string, object?>? JsSetProperty {{ get; set; }}\n        public static Action<object, string>? JsInitializeInstance {{ get; set; }}\n\n        public static void InitializeInstance(object instance, string typeName)\n        {{\n            JsInitializeInstance?.Invoke(instance, typeName);\n        }}\n\n        public static T InvokeMethod<T>(object instance, string methodName, object[] args)\n        {{\n            var callback = JsInvokeMethod ?? throw new InvalidOperationException(\"JsInvokeMethod callback is not registered.\");\n            var result = callback(instance, methodName, args);\n            return ConvertResult<T>(result);\n        }}\n\n        public static void InvokeVoid(object instance, string methodName, object[] args)\n        {{\n            var callback = JsInvokeVoid ?? throw new InvalidOperationException(\"JsInvokeVoid callback is not registered.\");\n            callback(instance, methodName, args);\n        }}\n\n        public static T GetProperty<T>(object instance, string propertyName)\n        {{\n            var callback = JsGetProperty ?? throw new InvalidOperationException(\"JsGetProperty callback is not registered.\");\n            var result = callback(instance, propertyName);\n            return ConvertResult<T>(result);\n        }}\n\n        public static void SetProperty(object instance, string propertyName, object? value)\n        {{\n            var callback = JsSetProperty ?? throw new InvalidOperationException(\"JsSetProperty callback is not registered.\");\n            callback(instance, propertyName, value);\n        }}\n\n        private static T ConvertResult<T>(object? value)\n        {{\n            if (value is null)\n            {{\n                return default!;\n            }}\n\n            if (value is T typed)\n            {{\n                return typed;\n            }}\n\n            return (T)Convert.ChangeType(value, typeof(T), CultureInfo.InvariantCulture);\n        }}\n    }}\n}}\n",
            GENERATED_FILE_HEADER
        );

        fs::write(project_dir.join("ProxyDispatcher.g.cs"), support)?;
        Ok(())
    }

    fn generate_assembly_info(&self, project_dir: &Path) -> Result<()> {
        let assembly_info = r#"using System.Reflection;

[assembly: AssemblyTitle("NSWinRTProxies")]
[assembly: AssemblyDescription("Static Binding Generator - Auto-generated WinRT proxy assembly")]
[assembly: AssemblyVersion("1.0.0.0")]
[assembly: AssemblyFileVersion("1.0.0.0")]
"#;

        let properties_dir = project_dir.join("Properties");
        fs::create_dir_all(&properties_dir)?;
        fs::write(properties_dir.join("AssemblyInfo.cs"), assembly_info)?;

        Ok(())
    }

    fn copy_app_sources(&self, project_dir: &Path) -> Result<usize> {
        // Copying developer-authored app C# sources into the generated proxy
        // project is opt-in only. Platform-specific app sources (XAML, UWP
        // types, tests) commonly prevent the generated project from building.
        // For now, do not copy any app sources by default; callers can set
        // `SBG_APP_CS_SOURCES_DIR` and modify this behavior if needed.
        Ok(0)
    }

    fn copy_cs_recursive(
        &self,
        root: &Path,
        current: &Path,
        destination_root: &Path,
        copied: &mut usize,
    ) -> Result<()> {
        for entry in fs::read_dir(current)? {
            let entry = entry?;
            let path = entry.path();
            if path.is_dir() {
                let folder_name = path
                    .file_name()
                    .and_then(|name| name.to_str())
                    .unwrap_or_default();
                if matches!(
                    folder_name,
                    "bin" | "obj" | "target" | "sbg_output" | ".git"
                ) {
                    continue;
                }
                self.copy_cs_recursive(root, &path, destination_root, copied)?;
                continue;
            }

            if path
                .extension()
                .is_some_and(|ext| ext.eq_ignore_ascii_case("cs"))
            {
                // Skip SDK/legacy assembly info files to avoid duplicate assembly attributes
                if path
                    .file_name()
                    .and_then(|n| n.to_str())
                    .map(|s| s.eq_ignore_ascii_case("AssemblyInfo.cs"))
                    .unwrap_or(false)
                {
                    continue;
                }
                let relative = path.strip_prefix(root).unwrap_or(path.as_path());
                let target = destination_root.join(relative);
                if let Some(parent) = target.parent() {
                    fs::create_dir_all(parent)?;
                }
                fs::copy(&path, &target)?;
                *copied += 1;
            }
        }

        Ok(())
    }
}

fn proxy_namespace(ext_meta: &ExtensionMetadata) -> String {
    ext_meta
        .namespace
        .clone()
        .or_else(|| {
            ext_meta
                .type_name
                .as_ref()
                .and_then(|name| name.rfind('.').map(|index| name[..index].to_string()))
        })
        .filter(|value| !value.trim().is_empty())
        .unwrap_or_else(|| "NativeScriptGeneratedProxies".to_string())
}

fn proxy_class_name(ext_meta: &ExtensionMetadata) -> String {
    sanitize_identifier(ext_meta.class_name.as_str())
}

fn proxy_base_type(ext_meta: &ExtensionMetadata) -> String {
    match ext_meta.base_class.as_deref().map(str::trim) {
        Some("") | None => "object".to_string(),
        Some(base) => normalize_csharp_type(base),
    }
}

fn sanitize_identifier(name: &str) -> String {
    let mut output = String::new();
    for (index, ch) in name.chars().enumerate() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            if index == 0 && ch.is_ascii_digit() {
                output.push('_');
            }
            output.push(ch);
        } else {
            output.push('_');
        }
    }

    if output.is_empty() {
        "GeneratedProxy".to_string()
    } else {
        output
    }
}

fn sanitize_parameter_name(name: &str, index: usize) -> String {
    let sanitized = sanitize_identifier(name);
    if sanitized == "GeneratedProxy" {
        format!("param_{}", index)
    } else {
        sanitized
    }
}

fn normalize_csharp_type(input: &str) -> String {
    match input.trim() {
        "void" | "Void" => "void".to_string(),
        "bool" | "Boolean" => "bool".to_string(),
        "string" | "String" => "string".to_string(),
        "object" | "Object" => "object".to_string(),
        "byte" | "UInt8" => "byte".to_string(),
        "sbyte" | "Int8" => "sbyte".to_string(),
        "short" | "Int16" => "short".to_string(),
        "ushort" | "UInt16" => "ushort".to_string(),
        "int" | "Int32" => "int".to_string(),
        "uint" | "UInt32" => "uint".to_string(),
        "long" | "Int64" => "long".to_string(),
        "ulong" | "UInt64" => "ulong".to_string(),
        "float" | "Single" => "float".to_string(),
        "double" | "Double" => "double".to_string(),
        other => other.to_string(),
    }
}

fn is_object_virtual(method_name: &str) -> bool {
    matches!(method_name, "ToString" | "Equals" | "GetHashCode" | "GetType")
}

fn csharp_string_literal(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}
